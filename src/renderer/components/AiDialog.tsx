import { useEffect, useState } from 'react';
import type { AiAnswer, AiStatus, AppSnapshot } from '../../shared/types';
import { api, errorText } from '../lib/api';
import { Modal, Time } from './common';

const SUGGESTIONS = ['Which saved locations overlap active weather alerts?', 'Summarize the current records for my selected properties.', 'What changed since the previous refresh?'];

export function AiDialog({ snap, selectedLocationId, onClose, onOpenSettings, onSelectRecord }: { snap: AppSnapshot; selectedLocationId: string | null; onClose(): void; onOpenSettings(): void; onSelectRecord(id: string): void }) {
  const [status, setStatus] = useState<AiStatus | null>(null);
  const [question, setQuestion] = useState('');
  const [scope, setScope] = useState<'all' | 'selected'>(selectedLocationId ? 'selected' : 'all');
  const [answer, setAnswer] = useState<AiAnswer | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    api.aiStatus().then(setStatus).catch((e) => setError(errorText(e)));
  }, []);

  async function ask(q: string) {
    if (!q.trim()) return;
    setBusy(true);
    setError(null);
    setAnswer(null);
    try {
      setAnswer(await api.aiAsk({ question: q, locationIds: scope === 'selected' && selectedLocationId ? [selectedLocationId] : [] }));
    } catch (e) {
      setError(errorText(e));
    } finally {
      setBusy(false);
    }
  }

  const ready = status?.enabled && status.reachable && !!snap.settings.ollamaModel && status.models.includes(snap.settings.ollamaModel);

  return (
    <Modal title="Ask the local AI" onClose={onClose} wide>
      {!status ? (
        <p className="muted">Checking local AI…</p>
      ) : !status.enabled ? (
        <div className="note">
          Local AI is turned off. It is optional: every core feature works without it.{' '}
          <button className="link-btn" onClick={onOpenSettings}>
            Open Settings
          </button>{' '}
          to enable it if you have Ollama installed.
        </div>
      ) : !status.reachable ? (
        <div className="note">
          AI unavailable: {status.error}{' '}
          <button className="link-btn" onClick={onOpenSettings}>
            Settings
          </button>
        </div>
      ) : !ready ? (
        <div className="note">
          Choose an installed model in{' '}
          <button className="link-btn" onClick={onOpenSettings}>
            Settings
          </button>
          .
        </div>
      ) : null}
      <p className="muted small">
        The model only explains results that Sky_View has already calculated (spatial matches, distances, feed freshness). It sees only the retrieved records and gets no file or network access. Feed text
        and notes are passed to it as untrusted data.
      </p>
      <div className="field-row">
        <label className="field grow">
          <span>Question</span>
          <input value={question} onChange={(e) => setQuestion(e.target.value)} onKeyDown={(e) => e.key === 'Enter' && void ask(question)} maxLength={1000} disabled={!ready || busy} />
        </label>
        <label className="field">
          <span>Scope</span>
          <select value={scope} onChange={(e) => setScope(e.target.value as typeof scope)}>
            <option value="all">All saved locations</option>
            <option value="selected" disabled={!selectedLocationId}>
              Selected location
            </option>
          </select>
        </label>
        <button className="btn primary" onClick={() => void ask(question)} disabled={!ready || busy || !question.trim()}>
          {busy ? 'Thinking…' : 'Ask'}
        </button>
      </div>
      <div className="btn-row">
        {SUGGESTIONS.map((s) => (
          <button
            key={s}
            className="btn small-btn"
            disabled={!ready || busy}
            onClick={() => {
              setQuestion(s);
              void ask(s);
            }}
          >
            {s}
          </button>
        ))}
      </div>
      {error && <div className="error-line">{error}</div>}
      {answer && (
        <div className="ai-answer">
          <div className="ai-label">
            AI-generated by local model <code>{answer.model}</code> · <Time iso={answer.generatedAt} /> · may be inaccurate. Verify with the source records.
          </div>
          <p className="pre">{answer.answer}</p>
          {answer.contextRecordIds.length > 0 && (
            <details>
              <summary>Records provided to the model ({answer.contextRecordIds.length})</summary>
              <ul className="small">
                {answer.contextRecordIds.map((id) => (
                  <li key={id}>
                    <button className="link-btn" onClick={() => onSelectRecord(id)}>
                      {id}
                    </button>
                  </li>
                ))}
              </ul>
            </details>
          )}
        </div>
      )}
    </Modal>
  );
}
